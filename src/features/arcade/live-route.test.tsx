import {seedAccountSession} from '../../test/account-session';
import {accountKey,ACCOUNT_SESSION} from './account-storage';
import React from 'react';
import {beforeEach,afterEach,it,expect,vi} from 'vitest';
import {render,screen,fireEvent,cleanup,waitFor} from '@testing-library/react';
import {RouterProvider,createMemoryHistory} from '@tanstack/react-router';
import {getRouter} from '../../router';
beforeEach(()=>{localStorage.clear();seedAccountSession();Element.prototype.scrollIntoView=vi.fn()});afterEach(cleanup);
it('loads a direct live URL, sends a chat message, awards a gift and returns to the list',async()=>{
 const router=getRouter();router.update({history:createMemoryHistory({initialEntries:['/ao-vivo?live=s0']})});await router.load();
 render(<RouterProvider router={router}/>);
 expect(await screen.findByRole('heading',{name:'CraftPedro',level:1})).toBeInTheDocument();
 expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
 expect(screen.getByRole('button',{name:'Reproduzir vídeo de amostra'})).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'Ocultar informações da live'}));
 expect(screen.getByRole('button',{name:'Mostrar informações da live'})).toHaveAttribute('aria-expanded','false');
 expect(screen.queryByRole('heading',{name:'CraftPedro',level:1})).not.toBeInTheDocument();
 expect(screen.getByRole('textbox',{name:'Mensagem na live'})).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'Mostrar informações da live'}));
 expect(screen.getByRole('heading',{name:'CraftPedro',level:1})).toBeInTheDocument();
 fireEvent.change(screen.getByRole('textbox',{name:'Mensagem na live'}),{target:{value:'Olá comunidade'}});
 fireEvent.click(screen.getByRole('button',{name:'Enviar mensagem na live'}));
 expect(screen.getByText('Olá comunidade')).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'Enviar 1 moeda. Saldo: 10 moedas'}));
 await waitFor(()=>expect(screen.getByText('enviou x1 Moeda!').closest('p')).toHaveTextContent('@playerone enviou x1 Moeda!'));
 expect(screen.getByText('enviou x1 Moeda!').closest('p')).toHaveClass('live-chat-gift');
 expect(screen.queryByText(/Moeda enviado!/)).not.toBeInTheDocument();
 await waitFor(()=>expect(JSON.parse(localStorage.getItem(accountKey('omlet-live-popularity-v1'))??'{}').s0).toBe(1));
 fireEvent.click(screen.getByRole('link',{name:'Voltar'}));
 await waitFor(()=>expect(router.state.location.search).toEqual({}));
 expect(await screen.findByRole('button',{name:/Ver live de CraftPedro:/})).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:/Ver live de CraftPedro:/}));
 await waitFor(()=>expect(router.state.location.search).toEqual({live:'s0'}));
 expect(await screen.findByRole('heading',{name:'CraftPedro',level:1})).toBeInTheDocument();
},30000);
it('handles an unknown live without breaking navigation',async()=>{
 const router=getRouter();router.update({history:createMemoryHistory({initialEntries:['/ao-vivo?live=missing']})});await router.load();render(<RouterProvider router={router}/>);
 expect(await screen.findByRole('heading',{name:'Live não encontrada'})).toBeInTheDocument();
 expect(screen.getByRole('link',{name:'Voltar'})).toBeInTheDocument();
},30000);
