import {RouterProvider,createMemoryHistory} from '@tanstack/react-router';
import {getRouter} from '../../router';
import {STORAGE_KEY} from './store';
beforeEach(()=>{localStorage.clear();Element.prototype.scrollIntoView=vi.fn()});afterEach(cleanup);
async function open(path:string){const router=getRouter();router.update({history:createMemoryHistory({initialEntries:[path]})});await router.load();render(<RouterProvider router={router}/>);return router}
const saved=()=>JSON.parse(localStorage.getItem(STORAGE_KEY)??'{}');
it('updates both sides of following, persists on reload and reverses when unfollowed',async()=>{
 const router=await open('/perfil?user=s3');
 expect(await screen.findByLabelText('Seguidores: 0')).toBeInTheDocument();
 const profile=document.querySelector('.user-profile-page')! as HTMLElement;
 fireEvent.click(within(profile).getAllByRole('button',{name:'Seguir Luna Plays'})[0]!);
 expect(within(profile).getByLabelText('Seguidores: 1')).toBeInTheDocument();
 await waitFor(()=>expect(saved().followed).toEqual(['Luna Plays']));
 await router.navigate({to:'/perfil',search:{user:undefined}});
 expect(await screen.findByLabelText('Seguindo: 1')).toBeInTheDocument();
 cleanup();await open('/perfil?user=s3');
 expect(await screen.findByLabelText('Seguidores: 1')).toBeInTheDocument();
 fireEvent.click(within(document.querySelector('.user-profile-page')! as HTMLElement).getAllByRole('button',{name:'Deixar de seguir Luna Plays'})[0]!);
 expect(screen.getByLabelText('Seguidores: 0')).toBeInTheDocument();
 await waitFor(()=>expect(saved().followed).toEqual([]));
},30000);
